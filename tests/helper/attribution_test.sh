#!/bin/bash
# tools/check-attribution.sh: attribution lines refused, ordinary messages and product wording accepted.
set -u
here=$(cd "$(dirname "$0")/../.." && pwd)
tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
fails=0
run() { printf '%b' "$2" > "$tmp"; if "$here/tools/check-attribution.sh" --message "$tmp" 2>/dev/null; then r=accepte; else r=refuse; fi
  if [[ $r == "$3" ]]; then echo "ok   $1"; else echo "FAIL $1 ($r)"; fails=$((fails + 1)); fi; }
run "co-auteur IA" 'fix: x\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>' refuse
run "co-auteur Copilot" 'fix: x\n\nCo-authored-by: Copilot <x@y>' refuse
run "co-auteur avec n avant le nom" 'fix: x\n\nCo-authored-by: Anon Assistant (OpenAI) <bot@example.com>' refuse
run "généré par, nom après des n" 'docs: x\n\nGenerated by an internal ChatGPT run' refuse
run "pied de page généré" 'docs: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)' refuse
run "émoji robot" 'feat: x 🤖' refuse
run "message normal" 'fix(security): rclone allow-list\n\nSigned-off-by: Yoan <y@users.noreply.github.com>' accepte
run "co-auteur humain" 'fix: x\n\nCo-authored-by: Alice <alice@example.com>' accepte
run "fonctionnalité IA du produit" 'docs: AI assistant extension supports Anthropic, OpenAI and Ollama providers' accepte
run "commentaire git ignoré" 'fix: x\n# Co-Authored-By: Claude' accepte
echo
if ((fails)); then echo "$fails échec(s)"; exit 1; fi
echo "Tous les tests passent."
